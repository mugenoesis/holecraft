// Turns three real OrcaSlicer project exports (made with 1, 4 and 16 filaments of the same preset) into
// packages/geometry/src/formats/orcaFilamentDefaults.ts: every project setting that is a per-filament
// list, with the preset's value for one filament. Run through scripts/update-orca-filament-defaults.sh.

import { readFileSync, writeFileSync } from 'node:fs';
import { readZip } from '@holecraft/geometry';

const [dir, output] = process.argv.slice(2) as [string, string];
const load = async (n: number) => {
	const zip = await readZip(new Uint8Array(readFileSync(`${dir}/ref${n}.3mf`)));
	const file = zip.get('Metadata/project_settings.config');
	if (!file) throw new Error(`ref${n}.3mf has no project settings`);
	return JSON.parse(new TextDecoder().decode(file)) as Record<string, unknown>;
};
const [one, four, sixteen] = [await load(1), await load(4), await load(16)];

// A per-filament list is one that grows with the number of filaments: 1, 4 and 16 entries in the three files.
const defaults: Record<string, string> = {};
for (const [key, value] of Object.entries(sixteen).sort(([a], [b]) => a.localeCompare(b))) {
	if (key === 'filament_colour') continue; // the palette sets this one
	const grows = (list: unknown, length: number) => Array.isArray(list) && list.length === length;
	if (grows(value, 16) && grows(four[key], 4) && grows(one[key], 1)) {
		const first = (value as unknown[])[0];
		if (typeof first !== 'string') throw new Error(`${key}: expected text values`);
		defaults[key] = first;
	}
}
if (Object.keys(defaults).length < 100)
	throw new Error(`only ${Object.keys(defaults).length} per-filament settings found; something is wrong`);

const lines = Object.entries(defaults).map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`);
writeFileSync(
	output,
	`// GENERATED by scripts/update-orca-filament-defaults.sh from OrcaSlicer's own engine (Generic PLA, Bambu preset).
// Do not edit by hand. These are the project settings that hold one value per filament; a project file
// needs every one of them to have as many entries as it has filaments, or the engine crashes on load.
export const ORCA_FILAMENT_DEFAULTS: Readonly<Record<string, string>> = Object.freeze({
${lines.join('\n')}
});
`,
);
console.log(`wrote ${Object.keys(defaults).length} per-filament settings to ${output}`);
