// Turns the bundled open fonts into plain outline data the app can use with no font reader and no file to download: for each font, the
// outlines (as path text), widths and boxes of the Basic Latin and Latin-1 letters, digits and punctuation. Written to
// packages/core/src/fonts/outlines/<font>.generated.ts (one file each) and fontIndex.generated.ts, and the licence texts to licenses/. Run by scripts/make-fonts.sh when a font is added or changed.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';

const require = createRequire(import.meta.url);
const opentype = require('opentype.js');

/** id is what a saved design stores, so never change or reuse one. */
const FONTS = [
	{ id: 1, key: 'sans', label: 'Sans', pkg: 'inter', file: 'inter-latin-700-normal.woff' },
	{ id: 2, key: 'serif', label: 'Serif', pkg: 'noto-serif', file: 'noto-serif-latin-700-normal.woff' },
	{ id: 3, key: 'mono', label: 'Mono', pkg: 'roboto-mono', file: 'roboto-mono-latin-700-normal.woff' },
	{ id: 4, key: 'script', label: 'Script', pkg: 'lobster', file: 'lobster-latin-400-normal.woff' },
	{ id: 5, key: 'rounded', label: 'Rounded', pkg: 'nunito', file: 'nunito-latin-700-normal.woff' },
	{ id: 6, key: 'condensed', label: 'Condensed', pkg: 'oswald', file: 'oswald-latin-700-normal.woff' },
	{ id: 7, key: 'caps', label: 'Caps', pkg: 'bebas-neue', file: 'bebas-neue-latin-400-normal.woff' },
	{ id: 8, key: 'display', label: 'Display', pkg: 'playfair-display', file: 'playfair-display-latin-700-normal.woff' },
	{ id: 9, key: 'handwriting', label: 'Handwriting', pkg: 'caveat', file: 'caveat-latin-700-normal.woff' },
	{ id: 10, key: 'brush', label: 'Brush', pkg: 'pacifico', file: 'pacifico-latin-400-normal.woff' },
];

const root = path.resolve(import.meta.dirname, '../..');
const round = (n) => Math.round(n * 10) / 10;
const code = (command) => {
	const n = (...keys) => keys.map((k) => round(command[k])).join(' ');
	if (command.type === 'M' || command.type === 'L') return `${command.type}${n('x', 'y')}`;
	if (command.type === 'Q') return `Q${n('x1', 'y1', 'x', 'y')}`;
	if (command.type === 'C') return `C${n('x1', 'y1', 'x2', 'y2', 'x', 'y')}`;
	return 'Z';
};

const codepoints = [...Array.from({ length: 95 }, (_, i) => 32 + i), ...Array.from({ length: 96 }, (_, i) => 160 + i)];
const out = {};
for (const f of FONTS) {
	const dir = path.join(root, 'node_modules/@fontsource', f.pkg);
	const buffer = readFileSync(path.join(dir, 'files', f.file));
	const font = opentype.parse(buffer.buffer.slice(buffer.byteOffset, buffer.byteOffset + buffer.byteLength));
	const glyphs = {};
	for (const cp of codepoints) {
		const glyph = font.charToGlyph(String.fromCodePoint(cp));
		if (glyph.index === 0) continue; // the font has no such letter
		const box = glyph.path.commands.length ? glyph.path.getBoundingBox() : null;
		glyphs[cp] = {
			advance: Math.round(glyph.advanceWidth),
			box: box ? [Math.round(box.x1), Math.round(box.y1), Math.round(box.x2), Math.round(box.y2)] : [0, 0, 0, 0],
			path: glyph.path.commands.map(code).join(''),
		};
	}
	out[f.key] = { id: f.id, label: f.label, unitsPerEm: font.unitsPerEm, ascender: font.ascender, descender: font.descender, glyphs };
	copyFileSync(path.join(dir, 'LICENSE'), path.join(root, 'licenses', `font-${f.pkg}-OFL.txt`));
	console.log(`${f.label} (${f.pkg}): ${Object.keys(glyphs).length} glyphs`);
}

const header = `// GENERATED by scripts/make-fonts.sh from the open fonts listed in licenses/ (SIL Open Font Licence 1.1): do not edit.
// The outlines are the fonts' own (Inter, Noto Serif, Roboto Mono, Nunito, Oswald, Playfair Display and Caveat in bold, and Lobster, Bebas Neue and Pacifico); see licenses/ for each notice and the licence.
`;
// One glyph per line, so a change to one font reads as a change to its own lines (and the file needs no formatter: biome leaves it alone).
const glyphLine = ([cp, g]) => `\t\t${cp}: ${JSON.stringify(g)},`;
const fontText = (f) =>
	[
		'export const FONT: FontData = {',
		`\tid: ${f.id},`,
		`\tlabel: ${JSON.stringify(f.label)},`,
		`\tunitsPerEm: ${f.unitsPerEm},`,
		`\tascender: ${f.ascender},`,
		`\tdescender: ${f.descender},`,
		'\tglyphs: {',
		...Object.entries(f.glyphs).map(glyphLine),
		'\t},',
		'};',
	].join('\n');

// One module per font, so a font that is not used is never loaded: the page and the geometry worker import each one only when a design needs it.
mkdirSync(path.join(root, 'packages/core/src/fonts/outlines'), { recursive: true });
for (const [key, f] of Object.entries(out)) {
	writeFileSync(
		path.join(root, `packages/core/src/fonts/outlines/${key}.generated.ts`),
		`${header}import type { FontData } from '../fontTypes.ts';\n\n${fontText(f)}\n`,
	);
}

// The list of fonts (id and name, which the Font choice shows without loading any outlines) and how to load each one.
const list = Object.values(out).map((f) => `\t{ id: ${f.id}, label: ${JSON.stringify(f.label)} },`);
const loaders = Object.entries(out).map(([key, f]) => `\t${f.id}: () => import('./outlines/${key}.generated.ts').then((m) => m.FONT),`);
writeFileSync(
	path.join(root, 'packages/core/src/fonts/fontIndex.generated.ts'),
	`${header}import type { FontData } from './fontTypes.ts';\n\n/** The fonts in the order the Font choice lists them. */\nexport const FONT_LIST: readonly { id: number; label: string }[] = [\n${list.join('\n')}\n];\n\n/** Each font's outlines load from their own file, the first time a design needs them. */\nexport const FONT_LOADERS: Record<number, () => Promise<FontData>> = {\n${loaders.join('\n')}\n};\n`,
);
